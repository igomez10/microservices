func (s *UserApiService) UpdateRolesForUser(ctx context.Context, username string, roles []string) (openapi.ImplResponse, error) {
	ctx, span := tracerhelper.GetTracer().Start(ctx, "UpdateRolesForUser")
	defer span.End()
	logger := contexthelper.GetLoggerInContext(ctx)
	tx, err := s.DBConn.Begin(ctx)
	if err != nil {
		logger.Error("Error starting transaction", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
		}, err
	}
	defer tx.Rollback(ctx)

	// verify the dbUser exists
	dbUser, errGetUser := s.DB.GetUserByUsername(ctx, tx, username)
	if errGetUser != nil {
		logger.Error("Error getting user", "error", errGetUser)
		return openapi.ImplResponse{
			Code: http.StatusNotFound,
			Body: openapi.Error{
				Code:    http.StatusNotFound,
				Message: "Error getting user",
			},
		}, nil
	}

	// verify all the roles exist
	dbRoles := make([]db.Role, len(roles))
	for i := range roles {
		dbRole, err := s.DB.GetRoleByName(ctx, tx, roles[i])
		if err != nil {
			logger.Error("Error getting role", "error", err)
			return openapi.ImplResponse{
				Code: http.StatusNotFound,
				Body: openapi.Error{
					Code:    http.StatusNotFound,
					Message: "Error getting role",
				},
			}, nil
		}
		dbRoles[i] = dbRole
	}

	// get all existing roles
	existingRoles, err := s.DB.GetUserRoles(ctx, tx, dbUser.ID)
	if err != nil {
		logger.Error("Error getting user roles", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusNotFound,
			Body: openapi.Error{
				Code:    http.StatusNotFound,
				Message: "Error getting user roles",
			},
		}, nil
	}

	newRoles := map[string]db.Role{}
	for _, role := range dbRoles {
		newRoles[role.Name] = role
	}

	oldRoles := map[string]db.Role{}
	for _, role := range existingRoles {
		oldRoles[role.Name] = role
	}

	// roles to add
	rolesToAdd := []string{}

	for i := range newRoles {
		if _, ok := oldRoles[i]; !ok {
			rolesToAdd = append(rolesToAdd, i)
		}
	}

	// roles to remove
	rolesToRemove := []string{}
	for i := range oldRoles {
		if _, ok := newRoles[i]; !ok {
			rolesToRemove = append(rolesToRemove, i)
		}
	}

	// add new roles
	for _, roleNameToAdd := range rolesToAdd {
		roleID := newRoles[roleNameToAdd].ID

		// Generate snowflake ID for the user-to-role association
		userToRoleID, err := s.SnowflakeGenerator.NextID()
		if err != nil {
			logger.Error("Error generating snowflake ID for user to role", "error", err)
			return openapi.ImplResponse{
				Code: http.StatusInternalServerError,
				Body: openapi.Error{
					Code:    http.StatusInternalServerError,
					Message: "Error generating ID",
				},
			}, nil
		}

		_, err = s.DB.CreateUserToRoleWithID(ctx, tx, db.CreateUserToRoleWithIDParams{
			ID:     userToRoleID,
			UserID: dbUser.ID,
			RoleID: roleID,
		})
		if err != nil {
			logger.Error("Error adding role to user", "error", err, "role", roleNameToAdd)
			return openapi.ImplResponse{
				Code: http.StatusInternalServerError,
				Body: openapi.Error{
					Code:    http.StatusInternalServerError,
					Message: "Error adding role to user",
				},
			}, nil
		}
	}

	// remove old roles
	for _, roleNameToRemove := range rolesToRemove {
		roleID := oldRoles[roleNameToRemove].ID
		err := s.DB.DeleteUserToRole(ctx, tx, db.DeleteUserToRoleParams{
			UserID: dbUser.ID,
			RoleID: roleID,
		})
		if err != nil {
			logger.Error("Error removing role from user", "error", err, "role", roleNameToRemove)
			return openapi.ImplResponse{
				Code: http.StatusInternalServerError,
				Body: openapi.Error{
					Code:    http.StatusInternalServerError,
					Message: "Error removing role from user",
				},
			}, nil
		}
	}

	if err := s.EventRecorder.RecordEvent(ctx, tx, eventRecorder.Event{
		AggregateID:   dbUser.ID,
		AggregateType: events.AggregateTypeUser,
		EventType:     events.EventTypeUserRolesUpdated,
		Payload:       events.UserRolesUpdated{UserID: dbUser.ID, Username: dbUser.Username, Roles: roles},
	}); err != nil {
		logger.Error("Error recording event", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	if err := tx.Commit(ctx); err != nil {
		logger.Error("Error committing transaction", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
		}, err
	}

	return openapi.Response(http.StatusOK, nil), nil
}
