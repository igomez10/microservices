const DEFAULT_ROLE_NAME = "administrator"

func (s *UserApiService) CreateUser(ctx context.Context, createUserReq openapi.CreateUserRequest) (openapi.ImplResponse, error) {
	ctx, span := tracerhelper.GetTracer().Start(ctx, "CreateUser")
	defer span.End()

	logger := contexthelper.GetLoggerInContext(ctx)
	// validate we don't have a user with the same username that is not deleted
	// start transaction
	tx, err := s.DBConn.BeginTx(ctx, pgx.TxOptions{})
	if err != nil {
		logger.Error("Error starting transaction", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}
	defer tx.Rollback(ctx)

	if _, err := s.DB.GetUserByUsername(ctx, tx, createUserReq.Username); err == nil {
		logger.Error("Username already exists", "error", err)
		return openapi.Response(http.StatusConflict, nil), nil
	}

	// validate we don't have a user with the same email that is not deleted
	if _, err := s.DB.GetUserByEmail(ctx, tx, createUserReq.Email); err == nil {
		logger.Error("Email already exists", "error", err)
		return openapi.Response(http.StatusConflict, nil), nil
	}

	// generate a random salt
	saltUUID, err := uuid.NewRandom()
	if err != nil {
		logger.Error("Error generating random string for salt", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}
	salt := base64.StdEncoding.EncodeToString([]byte(saltUUID.String()))

	hashedPasswordBase64 := EncryptPassword(createUserReq.Password, salt)
	//generate random email token confirmation
	// generate a random salt
	emailTokenUUID, err := uuid.NewRandom()
	if err != nil {
		logger.Error("Error generating random string for salt", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}
	emailToken := base64.StdEncoding.EncodeToString([]byte(emailTokenUUID.String()))

	// Generate a snowflake ID for the new user
	userID, err := s.SnowflakeGenerator.NextID()
	if err != nil {
		logger.Error("Error generating snowflake ID for user", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	// create the user with an autogenerated password that already expired
	params := db.CreateUserWithIDParams{
		ID:             userID,
		Username:       createUserReq.Username,
		FirstName:      createUserReq.FirstName,
		LastName:       createUserReq.LastName,
		Email:          createUserReq.Email,
		HashedPassword: hashedPasswordBase64,
		EmailToken:     emailToken,
		Salt:           salt,
		EmailVerifiedAt: pgtype.Timestamp{
			Time:  time.Now(),
			Valid: true,
		},
	}

	// get the default role id
	role, err := s.DB.GetRoleByName(ctx, tx, DEFAULT_ROLE_NAME)
	if err != nil {
		logger.Error("Error getting id of default role", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
			Body: openapi.Error{
				Code:    http.StatusInternalServerError,
				Message: "Error getting role id for user",
			},
		}, nil
	}

	createdUser, err := s.DB.CreateUserWithID(ctx, tx, params)
	if err != nil {
		logger.Error("Error creating user", "error", err)

		// Check if it's a duplicate key violation
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == pgerrcode.UniqueViolation {
			return openapi.ImplResponse{
				Code: http.StatusConflict,
				Body: openapi.Error{
					Code:    http.StatusConflict,
					Message: "User already exists",
				},
			}, nil
		}

		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	// attach the default role to the user
	// Generate a snowflake ID for the user to role
	userToRoleID, err := s.SnowflakeGenerator.NextID()
	if err != nil {
		logger.Error("Error generating snowflake ID for user to role", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}
	params2 := db.CreateUserToRoleWithIDParams{
		ID:     userToRoleID,
		UserID: createdUser.ID,
		RoleID: role.ID,
	}
	if _, err := s.DB.CreateUserToRoleWithID(ctx, tx, params2); err != nil {
		logger.Error(
			"Error attaching role to user",
			"error", err,
			"username", createUserReq.Username,
			"default_role", DEFAULT_ROLE_NAME,
		)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
			Body: openapi.Error{
				Code:    http.StatusInternalServerError,
				Message: "Error attaching default role to user",
			},
		}, nil
	}

	// create event
	userCreatedEvent := eventRecorder.Event{
		AggregateID:   createdUser.ID,
		AggregateType: events.AggregateTypeUser,
		EventType:     events.EventTypeUserCreated,
		Payload: events.UserCreated{
			UserID:    createdUser.ID,
			Username:  createdUser.Username,
			Email:     createdUser.Email,
			FirstName: createdUser.FirstName,
			LastName:  createdUser.LastName,
		},
	}
	if err := s.EventRecorder.RecordEvent(ctx, tx, userCreatedEvent); err != nil {
		logger.Error("Error recording event", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	// commit transaction
	if err := tx.Commit(ctx); err != nil {
		logger.Error("Error committing transaction", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	res := openapi.CreateUserResponse{
		Id:        strconv.FormatInt(createdUser.ID, 10),
		Username:  createdUser.Username,
		FirstName: createdUser.FirstName,
		LastName:  createdUser.LastName,
		Email:     createdUser.Email,
		CreatedAt: createdUser.CreatedAt.Time,
	}

	return openapi.Response(http.StatusOK, res), nil
}

func EncryptPassword(plaintextPassword string, salt string) string {
	saltedPassword := plaintextPassword + salt
	hashedPassword := sha256.Sum256([]byte(saltedPassword))
	hashedPasswordBase64 := base64.StdEncoding.EncodeToString(hashedPassword[:])
	return hashedPasswordBase64
}

// DeleteUser - Deletes a particular user
func (s *UserApiService) DeleteUser(ctx context.Context, username string) (openapi.ImplResponse, error) {
	ctx, span := tracerhelper.GetTracer().Start(ctx, "DeleteUser")
	defer span.End()
	logger := contexthelper.GetLoggerInContext(ctx)

	tx, err := s.DBConn.Begin(ctx)
	if err != nil {
		logger.Error("Error starting transaction", "error", err)
		return openapi.ImplResponse{Code: http.StatusInternalServerError}, nil
	}
	defer tx.Rollback(ctx)

	// look up the user first so the event can reference its aggregate id
	existingUser, err := s.DB.GetUserByUsername(ctx, tx, username)
	if err != nil {
		logger.Error("Error getting user", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusNotFound,
			Body: openapi.Error{
				Code:    http.StatusNotFound,
				Message: "Error deleting user",
			},
		}, nil
	}

	if err := s.DB.DeleteUserByUsername(ctx, tx, username); err != nil {
		logger.Error("Error deleting user", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusNotFound,
			Body: openapi.Error{
				Code:    http.StatusNotFound,
				Message: "Error deleting user",
			},
		}, nil
	}

	if err := s.EventRecorder.RecordEvent(ctx, tx, eventRecorder.Event{
		AggregateID:   existingUser.ID,
		AggregateType: events.AggregateTypeUser,
		EventType:     events.EventTypeUserDeleted,
		Payload:       events.UserDeleted{UserID: existingUser.ID, Username: existingUser.Username},
	}); err != nil {
		logger.Error("Error recording event", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	if err := tx.Commit(ctx); err != nil {
		logger.Error("Error committing transaction", "error", err)
		return openapi.ImplResponse{Code: http.StatusInternalServerError}, nil
	}

	return openapi.Response(http.StatusOK, nil), nil
}

