func (s *UserApiService) ChangePassword(ctx context.Context, req openapi.ChangePasswordRequest) (openapi.ImplResponse, error) {
	ctx, span := tracerhelper.GetTracer().Start(ctx, "user.changePassword")
	defer span.End()
	logger := contexthelper.GetLoggerInContext(ctx)

	tx, err := s.DBConn.Begin(ctx)
	if err != nil {
		logger.Error("Error starting transaction", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
		}, err
	}
	defer tx.Rollback(ctx)

	// get user from request context
	username, ok := contexthelper.GetUsernameInContext(ctx)
	if !ok {
		logger.Error("Error getting user from context")
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
			Body: openapi.Error{
				Code:    http.StatusInternalServerError,
				Message: "Error getting user from context",
			},
		}, nil
	}

	// validate the user exists
	createUserReq, errGetUser := s.DB.GetUserByUsername(ctx, tx, username)
	if errGetUser != nil {
		logger.Error("Error getting user", "error", errGetUser)
		return openapi.ImplResponse{
			Code: http.StatusNotFound,
			Body: openapi.Error{
				Code:    http.StatusNotFound,
				Message: "Error getting user",
			},
		}, nil
	}

	// validate the old password is correct
	encryptedHashedOldPassword := EncryptPassword(req.OldPassword, createUserReq.Salt)
	if encryptedHashedOldPassword != createUserReq.HashedPassword {
		logger.Error("Error validating old password")

		return openapi.ImplResponse{
			Code: http.StatusUnauthorized,
			Body: openapi.Error{
				Code:    http.StatusUnauthorized,
				Message: "Error validating old password",
			},
		}, nil
	}

	// hash the new password but keep the same salt
	encryptedHashedNewPassword := EncryptPassword(req.NewPassword, createUserReq.Salt)

	// update the password
	params := db.UpdateUserParams{
		ID:                      createUserReq.ID,
		HashedPassword:          string(encryptedHashedNewPassword),
		Username:                createUserReq.Username,
		FirstName:               createUserReq.FirstName,
		LastName:                createUserReq.LastName,
		Email:                   createUserReq.Email,
		Salt:                    createUserReq.Salt,
		HashedPasswordExpiresAt: createUserReq.HashedPasswordExpiresAt,
		EmailToken:              createUserReq.EmailToken,
		EmailVerifiedAt:         createUserReq.EmailVerifiedAt,
		UpdatedAt: pgtype.Timestamp{
			Time:  time.Now(),
			Valid: true,
		},
	}

	if err := s.DB.UpdateUser(ctx, tx, params); err != nil {
		logger.Error("Error updating password", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
			Body: openapi.Error{
				Code:    http.StatusInternalServerError,
				Message: "Error updating password",
			},
		}, nil
	}

	if err := s.EventRecorder.RecordEvent(ctx, tx, eventRecorder.Event{
		AggregateID:   createUserReq.ID,
		AggregateType: events.AggregateTypeUser,
		EventType:     events.EventTypeUserPasswordChanged,
		Payload:       events.UserPasswordChanged{UserID: createUserReq.ID, Username: createUserReq.Username},
	}); err != nil {
		logger.Error("Error recording event", "error", err)
		return openapi.Response(http.StatusInternalServerError, nil), nil
	}

	if err := tx.Commit(ctx); err != nil {
		logger.Error("Error committing transaction", "error", err)
		return openapi.ImplResponse{
			Code: http.StatusInternalServerError,
		}, err
	}

	apiUser := converter.FromDBUserToAPIUser(createUserReq)
	return openapi.Response(http.StatusOK, apiUser), nil
}

