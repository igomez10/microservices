package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

type OpenAPISpec struct {
	Components Components `yaml:"components"`
}

type Components struct {
	SecuritySchemes map[string]SecurityScheme `yaml:"securitySchemes"`
}

type SecurityScheme struct {
	Type  string `yaml:"type"`
	Flows Flows  `yaml:"flows"`
}

type Flows struct {
	ClientCredentials ClientCredentials `yaml:"clientCredentials"`
}

type ClientCredentials struct {
	TokenURL string            `yaml:"tokenUrl"`
	Scopes   map[string]string `yaml:"scopes"`
}

type ScopeData struct {
	ConstName   string
	Value       string
	Description string
}

const generatedFileTemplate = `// Code generated by tools/scopegen. DO NOT EDIT.
// Source: openapi.yaml

// Package scopes contains OAuth2 scope constants for the Socialapp API.
// This package provides type-safe constants for all OAuth2 scopes defined in the OpenAPI specification.
package scopes

// Scope represents an OAuth2 scope string.
type Scope string

// String returns the string representation of the scope.
func (s Scope) String() string {
	return string(s)
}

// IsValid checks if the scope is a valid known scope.
func (s Scope) IsValid() bool {
	_, ok := scopeMap[s]
	return ok
}

// Description returns the human-readable description of the scope.
func (s Scope) Description() string {
	return scopeMap[s]
}

const (
{{- range .Scopes}}
	// {{.ConstName}} - {{.Description}}
	{{.ConstName}} Scope = "{{.Value}}"
{{end}}
)

// AllScopes returns a slice of all valid scopes.
func AllScopes() []Scope {
	return []Scope{
{{- range .Scopes}}
		{{.ConstName}},
{{end}}
	}
}

// scopeMap maps scope values to their descriptions for validation and lookup.
var scopeMap = map[Scope]string{
{{- range .Scopes}}
	{{.ConstName}}: "{{.Description}}",
{{end}}
}

// FromString converts a string to a Scope and returns whether it's valid.
func FromString(s string) (Scope, bool) {
	scope := Scope(s)
	return scope, scope.IsValid()
}

// MustFromString converts a string to a Scope and panics if it's not valid.
func MustFromString(s string) Scope {
	scope, ok := FromString(s)
	if !ok {
		panic(fmt.Sprintf("invalid scope: %s", s))
	}
	return scope
}
`

func main() {
	inputFile := flag.String("input", "openapi.yaml", "Path to the OpenAPI spec file")
	outputFile := flag.String("output", "pkg/scopes/scopes.go", "Path to the output Go file")
	flag.Parse()

	// Read the OpenAPI spec
	data, err := os.ReadFile(*inputFile)
	if err != nil {
		log.Fatalf("Failed to read input file: %v", err)
	}

	// Parse the YAML
	var spec OpenAPISpec
	if err := yaml.Unmarshal(data, &spec); err != nil {
		log.Fatalf("Failed to parse YAML: %v", err)
	}

	// Extract OAuth2 scopes
	oauth2Scheme, ok := spec.Components.SecuritySchemes["OAuth2"]
	if !ok {
		log.Fatal("OAuth2 security scheme not found in the spec")
	}

	if len(oauth2Scheme.Flows.ClientCredentials.Scopes) == 0 {
		log.Fatal("No scopes found in OAuth2 client credentials flow")
	}

	// Convert scopes to ScopeData
	var scopes []ScopeData
	for scopeValue, description := range oauth2Scheme.Flows.ClientCredentials.Scopes {
		scopes = append(scopes, ScopeData{
			ConstName:   toConstName(scopeValue),
			Value:       scopeValue,
			Description: description,
		})
	}

	// Sort scopes by constant name for consistent output
	sort.Slice(scopes, func(i, j int) bool {
		return scopes[i].ConstName < scopes[j].ConstName
	})

	// Generate the Go file
	tmpl, err := template.New("scopes").Parse(generatedFileTemplate)
	if err != nil {
		log.Fatalf("Failed to parse template: %v", err)
	}

	// Create output directory if it doesn't exist
	outputDir := strings.TrimSuffix(*outputFile, "/scopes.go")
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		log.Fatalf("Failed to create output directory: %v", err)
	}

	// Create output file
	outFile, err := os.Create(*outputFile)
	if err != nil {
		log.Fatalf("Failed to create output file: %v", err)
	}
	defer outFile.Close()

	// Execute template
	data_for_template := map[string]interface{}{
		"Scopes": scopes,
	}

	if err := tmpl.Execute(outFile, data_for_template); err != nil {
		log.Fatalf("Failed to execute template: %v", err)
	}

	fmt.Printf("Successfully generated %s with %d scopes\n", *outputFile, len(scopes))
}

// toConstName converts a scope string to a Go constant name.
// Example: "socialapp.users.list" -> "SocialappUsersList"
// Example: "shortly.url.delete" -> "ShortlyUrlDelete"
func toConstName(scope string) string {
	// Replace dots and hyphens with spaces for splitting
	scope = strings.ReplaceAll(scope, ".", " ")
	scope = strings.ReplaceAll(scope, "-", " ")
	scope = strings.ReplaceAll(scope, "_", " ")

	// Split into words
	words := strings.Fields(scope)

	// Capitalize each word
	for i, word := range words {
		words[i] = strings.Title(strings.ToLower(word))
	}

	// Join without separators
	return strings.Join(words, "")
}
